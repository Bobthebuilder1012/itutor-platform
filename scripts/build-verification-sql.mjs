// Builds docs/apply-verification-migrations.sql and docs/rollback-verification-migrations.sql
// from supabase/migrations/252-257 and supabase/rollbacks/252-257. It only concatenates:
// each file's own BEGIN/COMMIT is removed and ONE transaction wraps the lot, so either
// every change lands or none does. Run: node scripts/build-verification-sql.mjs
import { readFileSync, writeFileSync } from 'fs';

const names = [
  '252_teacher_verification_v2',
  '253_verification_security_hardening',
  '254_verification_v2_review',
  '255_verification_v2_redaction_deletion',
  '256_identity_providers',
  '257_identity_outcomes',
];
// The 252 rollback ends with a bucket delete ("Part B") that must NOT sit inside the
// transaction: it errors while the bucket holds files, and Supabase may refuse direct
// deletes on storage tables. It is re-added at the end as a commented, run-alone step.
const PART_B = '-- ---------- Part B';
const strip = (sql) => sql.split(PART_B)[0].replace(/\r\n/g, '\n').replace(/^[ \t]*(BEGIN|COMMIT);[ \t]*$/gm, '').trim();

function build(title, intro, files, banner) {
  const parts = files.map((f) => `-- ${'='.repeat(60)}\n-- ${banner(f)}\n-- ${'='.repeat(60)}\n\n${strip(readFileSync(f.path, 'utf8'))}\n`);
  return `${title}\n${intro}\n\nBEGIN;\n\n${parts.join('\n')}\nCOMMIT;\n`;
}

const apply = build(
  `-- =====================================================================
-- APPLY: teacher verification v2 (migrations 252 to 257), ONE transaction
-- =====================================================================
-- GENERATED by scripts/build-verification-sql.mjs. Do not edit by hand; edit the
-- migrations and rebuild. Written, NOT applied anywhere.
--
-- ORDER: 1) run docs/pre-check-notifications.sql and read every result,
--        2) run this file once in the STAGING SQL Editor,
--        3) if anything is wrong, run docs/rollback-verification-migrations.sql.
--
-- If any statement fails the whole transaction rolls back and nothing is changed.
-- Safe to run twice (CREATE ... IF NOT EXISTS, DROP ... IF EXISTS before CREATE).
--
-- NOT PURELY ADDITIVE (see docs/staging-handoff.md, "Migration risks"): it also
-- rewrites two CHECK constraints (profiles.tutor_verification_status,
-- notifications_type_check) and adds guard triggers on existing tables.
-- =====================================================================`,
  '',
  names.map((n) => ({ path: `supabase/migrations/${n}.sql`, n })),
  (f) => `from supabase/migrations/${f.n}.sql`
);

const rollback = build(
  `-- =====================================================================
-- ROLLBACK: teacher verification v2 (undoes 257 down to 252), ONE transaction
-- =====================================================================
-- GENERATED by scripts/build-verification-sql.mjs from supabase/rollbacks/.
-- DESTRUCTIVE: it drops the v2 tables, so every verification row, credential,
-- decision and identity outcome is DELETED. Export what you need first.
-- It does not touch the old verification tables. It DOES change profiles: a teacher
-- whose profile says REVOKED or REVERIFICATION_REQUIRED is set to REJECTED, and the
-- narrower CHECK constraints are restored. It leaves the notifications constraint
-- widened (harmless) and the storage bucket in place (see the last lines).
-- Run it only if the apply file went wrong or the test is abandoned.
-- Run after turning VERIFICATION_V2_ENABLED off.
-- =====================================================================`,
  '',
  [...names].reverse().map((n) => ({ path: `supabase/rollbacks/${n}_rollback.sql`, n })),
  (f) => `undoes ${f.n}`
);

const partB = [
  '',
  '-- =====================================================================',
  '-- OPTIONAL, run ALONE afterwards, only if the bucket is empty (or delete the bucket',
  '-- "tutor-credential-proofs" in Dashboard > Storage). Leaving it is harmless: it is private.',
  '-- =====================================================================',
  "-- DELETE FROM storage.buckets WHERE id = 'tutor-credential-proofs';",
  '',
].join('\n');
writeFileSync('docs/apply-verification-migrations.sql', apply);
writeFileSync('docs/rollback-verification-migrations.sql', rollback + partB);
console.log('apply lines:', apply.split('\n').length, ' rollback lines:', rollback.split('\n').length);
